export function hasGlyph(ch) {
  return Object.prototype.hasOwnProperty.call(G, ch.toUpperCase());
}

// Trả về mảng 7 số nguyên (5 bit mỗi hàng) của glyph
export function glyphRows(ch) {
  const rows = G[ch.toUpperCase()];
  if (!rows) return G[" "].map(() => 0);
  return rows.map((r) => {
    let v = 0;
    for (let i = 0; i < 5; i++) if (r[i] === "#") v |= 1 << (4 - i);
    return v;
  });
}
